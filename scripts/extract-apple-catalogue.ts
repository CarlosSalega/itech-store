import { mkdir, writeFile } from "node:fs/promises";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";

import type { Category } from "../src/generated/prisma/enums";

import {
	categoryFromName,
	normaliseName,
	REQUESTED_APPLE_PRODUCTS,
	selectRequested,
	skuFor,
	slugFromName,
	storagesFromName,
} from "../src/features/catalog/apple-catalogue";
import { preserveLocalPhotographs } from "../src/features/catalog/image-preservation";
import { familyFolder } from "../src/features/catalog/source-mapping";

/**
 * Extraction of the Apple products this store does not sell yet into files the project
 * owns: `prisma/seed/products-apple.json` plus local photography.
 *
 * The base address is read from `APPLE_SOURCE_URL` and is deliberately never printed,
 * stored or defaulted: the repository must carry no reference to the source, and this
 * script must never reach for a `.env` file on its own (no dotenv import here, on
 * purpose).
 *
 * Run: pnpm tsx scripts/extract-apple-catalogue.ts [--dry-run] [--limit=N]
 *
 * Nothing but product names, families, slugs and counts is printed. Prices, stock and
 * provenance are absent on purpose: prices and stock are sample data generated by the
 * seed, and where a row came from is not something this repository records.
 */

const BASE_URL = process.env.APPLE_SOURCE_URL;
const ROOT = process.cwd();
const DATA_FILE = path.join(ROOT, "prisma", "seed", "products-apple.json");

/**
 * The list of products to import lives next to the classifier that reads the names
 * (`REQUESTED_APPLE_PRODUCTS` in `src/features/catalog/apple-catalogue.ts`) so that a test
 * can prove every entry resolves to a family. This script only consumes it.
 */

/**
 * Description copy per family. Written here rather than taken from the source: the
 * source's prose carries its own store identity, and its claims about stock, warranty or
 * condition are not this store's claims to make.
 */
const DESCRIPTION: Record<Category, string> = {
	IPHONE: "iPhone. Consultanos por colores, capacidad y disponibilidad.",
	IPAD: "iPad. Consultanos por capacidad, conectividad y disponibilidad.",
	MAC: "Mac. Consultanos por configuración y disponibilidad.",
	WATCH: "Apple Watch. Consultanos por correas y disponibilidad.",
	AIRPODS: "AirPods. Consultanos por disponibilidad.",
	ACCESSORY: "Accesorio de Apple. Consultanos por compatibilidad.",
};

type SourceRow = {
	/** The Apple product name, as the source spells it. */
	name: string;
	/** Where the photograph lives, resolved to an absolute address. */
	image: string;
};

type CatalogueVariant = { sku: string; storage: string | null };

type CatalogueProduct = {
	slug: string;
	name: string;
	description: string;
	category: Category;
	images: string[];
	variants: CatalogueVariant[];
};

/** Never leak an address into a log line. */
function safeMessage(error: unknown): string {
	const message = error instanceof Error ? error.message : String(error);

	return message.replace(/https?:\/\/[^\s"']+/g, "<url>");
}

function decodeEntities(value: string): string {
	return value
		.replace(/&quot;/g, '"')
		.replace(/&#0?39;/g, "'")
		.replace(/&apos;/g, "'")
		.replace(/&lt;/g, "<")
		.replace(/&gt;/g, ">")
		.replace(/&nbsp;/g, " ")
		.replace(/&amp;/g, "&");
}

function attribute(tag: string, name: string): string | null {
	const match = new RegExp(`\\b${name}\\s*=\\s*"([^"]*)"`, "i").exec(tag);

	return match ? decodeEntities(match[1]) : null;
}

/**
 * Reads the catalogue out of one listing page. Every product card carries the name as the
 * photograph's alternative text, which is the only stable pairing between a name and its
 * picture and needs no knowledge of the page's markup beyond the `img` tag.
 */
function parseRows(html: string): SourceRow[] {
	const rows: SourceRow[] = [];

	for (const tag of html.match(/<img\b[^>]*>/gi) ?? []) {
		const name = attribute(tag, "alt")?.trim() ?? "";
		const src = attribute(tag, "src");

		if (name === "" || src === null || src === "") {
			continue;
		}

		rows.push({ name, image: new URL(src, BASE_URL).toString() });
	}

	return rows;
}

async function fetchText(address: string): Promise<string> {
	const response = await fetch(address, {
		headers: { "user-agent": "Mozilla/5.0 (compatible; catalogue-extraction)" },
	});

	if (!response.ok) {
		throw new Error(`listing request failed with status ${response.status}`);
	}

	return response.text();
}

async function downloadImage(
	row: SourceRow,
	slug: string,
	family: Category,
): Promise<string> {
	const response = await fetch(row.image, {
		headers: { "user-agent": "Mozilla/5.0 (compatible; catalogue-extraction)" },
	});

	if (!response.ok) {
		throw new Error(`photograph request failed with status ${response.status}`);
	}

	const bytes = Buffer.from(await response.arrayBuffer());

	// A landing page, an error page or an HTML redirect would otherwise be written to
	// disk as if it were a photograph.
	if (bytes.subarray(0, 4).toString("ascii") !== "RIFF" || bytes.subarray(8, 12).toString("ascii") !== "WEBP") {
		throw new Error("photograph is not a webp file");
	}

	// The reference and the file share the family folder, so the photograph can never
	// land at the flat root where nothing is served from any more.
	const reference = `${familyFolder(family)}/${slug}-1.webp`;
	const destination = path.join(ROOT, "public", reference);

	await mkdir(path.dirname(destination), { recursive: true });
	await writeFile(destination, bytes);

	return reference;
}

function flagValue(name: string): number | null {
	const prefix = `--${name}=`;
	const match = process.argv.find((argument) => argument.startsWith(prefix));

	if (!match) {
		return null;
	}

	const parsed = Number.parseInt(match.slice(prefix.length), 10);

	return Number.isFinite(parsed) && parsed > 0 ? parsed : null;
}

async function main(): Promise<void> {
	const dryRun = process.argv.includes("--dry-run");
	const limit = flagValue("limit");

	if (!BASE_URL) {
		throw new Error("APPLE_SOURCE_URL is not set");
	}

	const rows = parseRows(await fetchText(BASE_URL));
	const selection = selectRequested(
		rows.map((row) => row.name),
		REQUESTED_APPLE_PRODUCTS,
	);
	const wanted = limit === null ? selection.present : selection.present.slice(0, limit);

	// One photograph per selected product; a name the page repeats must not be fetched
	// twice. The key is the compared form, because the source may spell the brand twice
	// and the store names the product once.
	const rowByName = new Map<string, SourceRow>();

	for (const row of rows) {
		const key = normaliseName(row.name);

		if (!rowByName.has(key)) {
			rowByName.set(key, row);
		}
	}

	const products: CatalogueProduct[] = [];
	const slugs = new Set<string>();
	const skipped: string[] = [];
	let preservedCount = 0;

	// Photographs added by hand live in the same array this run rewrites, so a plain
	// rewrite deletes the owner's work and reports success. Read what is there first.
	const previousImages = new Map<string, string[]>();

	if (!dryRun && existsSync(DATA_FILE)) {
		for (const product of JSON.parse(readFileSync(DATA_FILE, "utf8")) as CatalogueProduct[]) {
			previousImages.set(product.slug, product.images);
		}
	}

	for (const name of wanted) {
		const row = rowByName.get(normaliseName(name));
		const category = categoryFromName(name);

		if (row === undefined || category === null) {
			skipped.push(`${name} (no usable row or family)`);
			continue;
		}

		const slug = slugFromName(name);

		if (slugs.has(slug)) {
			throw new Error(`two products resolve to the same address: ${slug}`);
		}

		slugs.add(slug);

		const storages = storagesFromName(name);
		const variants: CatalogueVariant[] =
			storages.length === 0
				? [{ sku: skuFor(slug, null), storage: null }]
				: storages.map((storage) => ({ sku: skuFor(slug, storage), storage }));

		const downloaded = dryRun ? [] : [await downloadImage(row, slug, category)];
		const preserved = preserveLocalPhotographs(
			downloaded,
			previousImages.get(slug) ?? null,
		);

		preservedCount += preserved.preserved.length;

		products.push({
			slug,
			name,
			description: DESCRIPTION[category],
			category,
			images: preserved.images,
			variants,
		});

		console.log(
			`  ${category.padEnd(9)} ${slug.padEnd(30)} ${variants.length} variant(s)`,
		);
	}

	if (dryRun) {
		console.log("\nDry run: no photograph downloaded and no data written.");
	} else {
		await writeFile(DATA_FILE, `${JSON.stringify(products, null, "\t")}\n`);
		console.log(`\nWrote ${products.length} product(s) and their photographs.`);
		console.log(`Photographs kept from the existing file: ${preservedCount}`);
	}

	console.log(`Rows read from the listing: ${rows.length}`);
	console.log(`Products imported: ${products.length}`);

	if (skipped.length > 0) {
		console.log(`Rows skipped: ${skipped.length}`);
		for (const entry of skipped) {
			console.log(`  ${entry}`);
		}
	}

	// Loud on purpose: a rename upstream must not remove a product from the store in
	// silence, and a request that matched nothing means the page changed shape.
	if (selection.missing.length > 0) {
		console.log(`\nRequested but not listed: ${selection.missing.length}`);
		for (const name of selection.missing) {
			console.log(`  ${name}`);
		}
	}
}

main().catch((error: unknown) => {
	console.error(`Extraction failed: ${safeMessage(error)}`);
	process.exitCode = 1;
});
